// A static, offline-first cover editor entry. The app and its supplied screenshots are handed in as plain files.
import { cpSync, existsSync, mkdirSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildDossier } from './vendor/makefun-app.ts';

const here = fileURLToPath(new URL('.', import.meta.url));
const out = process.env.MAKEFUN_OUTPUT_DIR ?? '/output';
const sourceScreenshots = join(here, 'screenshots');
if (!existsSync(sourceScreenshots) || !statSync(sourceScreenshots).isDirectory() || readdirSync(sourceScreenshots).filter((name) => !name.startsWith('.')).length === 0) {
  throw new Error(`Cannot build entry: screenshots/ is missing or empty at ${sourceScreenshots}`);
}

mkdirSync(out, { recursive: true });
cpSync(join(here, 'app'), join(out, 'app'), { recursive: true });
mkdirSync(join(out, 'screenshots'), { recursive: true });
cpSync(sourceScreenshots, join(out, 'screenshots'), { recursive: true });

writeFileSync(
  join(out, 'dossier.json'),
  buildDossier(out, {
    text_max_bytes: 163840,
    screenshots: { max: 4, max_bytes: 262144 },
    app_max_files: 993,
    app_max_bytes: 50331648,
    app_path_max_bytes: 1000,
  }),
);
